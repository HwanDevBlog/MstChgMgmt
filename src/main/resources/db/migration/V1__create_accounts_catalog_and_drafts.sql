-- 계정과 역할은 초기 데이터로만 관리하며 앱 계정에는 조회 권한만 부여한다.
CREATE TABLE app_user (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(50) NOT NULL UNIQUE,
    password_hash varchar(100) NOT NULL,
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE user_role (
    user_id bigint NOT NULL REFERENCES app_user(id),
    role varchar(20) NOT NULL CHECK (role IN ('REQUESTER', 'APPROVER', 'VIEWER')),
    PRIMARY KEY (user_id, role)
);

CREATE TABLE equipment (
    code varchar(9) PRIMARY KEY CHECK (code ~ '^EQ-[A-Z0-9]{6}$'),
    name varchar(100) NOT NULL,
    category varchar(20) NOT NULL CHECK (category IN ('CAMERA', 'AUDIO', 'LIGHTING', 'ACCESSORY')),
    daily_fee_krw bigint NOT NULL CHECK (daily_fee_krw >= 0),
    active boolean NOT NULL,
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0)
);

CREATE TABLE change_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id bigint NOT NULL REFERENCES app_user(id),
    current_revision_id bigint,
    created_at timestamptz NOT NULL
);

CREATE TABLE change_revision (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL REFERENCES change_request(id),
    revision_number integer NOT NULL CHECK (revision_number > 0),
    state varchar(20) NOT NULL CHECK (state IN ('DRAFT', 'SUBMITTED', 'APPLIED', 'REJECTED', 'WITHDRAWN')),
    reason varchar(500) NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL,
    UNIQUE (request_id, revision_number),
    UNIQUE (request_id, id)
);

-- 다른 요청의 리비전을 현재 포인터로 지정하는 오류도 DB에서 차단한다.
ALTER TABLE change_request ADD CONSTRAINT fk_current_revision
    FOREIGN KEY (id, current_revision_id) REFERENCES change_revision(request_id, id);

CREATE INDEX ix_request_owner ON change_request(requester_id, id);


GRANT SELECT ON app_user, user_role, equipment TO mcr_app;
GRANT SELECT, INSERT, UPDATE ON change_request, change_revision TO mcr_app;
GRANT USAGE, SELECT ON SEQUENCE change_request_id_seq, change_revision_id_seq TO mcr_app;
